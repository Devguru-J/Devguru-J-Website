export interface Work {
  slug: string;
  /** 목록·상세 상단에 표시되는 번호 */
  no: string;
  title: string;
  titleEn: string;
  /** 카드에 걸리는 한 줄. 제품이 무엇을 하는지 먼저 읽히도록. */
  summary: string;
  category: string;
  year: string;
  platform: string;
  role: string;
  /** 상세 페이지 리드 문단 */
  lead: string;
  /** 상세 페이지 본문 — 제목 + 문단들 */
  sections: { heading: string; body: string[] }[];
  /** 상세 페이지 하단 요약 리스트 */
  notes: string[];
  cover?: string;
  /** 외부 링크 (있을 때만 노출) */
  link?: { label: string; href: string };
  /**
   * true 이면 사이트에 노출되지 않습니다.
   * 내용을 다 채운 뒤 이 줄을 지우거나 false 로 바꾸면 공개됩니다.
   * 자리표시자가 실수로 배포되는 것을 막기 위한 장치입니다.
   */
  draft?: boolean;
}

